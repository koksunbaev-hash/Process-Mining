  function known(value) {
    return SUPPORTED.indexOf(value) >= 0 ? value : null;
  }

  /* Подстановка {скобок}. Пропущенный параметр оставляем как есть: пустое
   * место в тексте прячет ошибку, а «{count}» на экране её показывает. */
  function fill(text, params) {
    if (!params) return text;
    return text.replace(/\{(\w+)\}/g, function (whole, name) {
      return params[name] === undefined || params[name] === null ? whole : params[name];
    });
  }

  function t(key, params) {
    if (lang === "ru") return fill(key, params);
    var row = DICT[key];
    // Нет перевода - русский оригинал. Экран остаётся рабочим, а пропуск
    // виден глазом: наполовину переведённая страница заметнее пустоты.
    if (!row) return fill(key, params);
    return fill(lang === "kk" ? row[0] : row[1], params);
  }

  /* Форма существительного при числе. Русскому нужны три формы, английскому
   * две, казахскому - одна: «24 кейс», без окончания. */
  function plural(count, key) {
    var forms = PLURALS[key] && PLURALS[key][lang];
    if (!forms) return key;
    if (forms.length === 1) return forms[0];
    if (lang === "en") return Math.abs(count) === 1 ? forms[0] : forms[1];
    var tail = Math.abs(count) % 10;
    var teen = Math.abs(count) % 100;
    if (teen >= 11 && teen <= 14) return forms[2];
    if (tail === 1) return forms[0];
    if (tail >= 2 && tail <= 4) return forms[1];
    return forms[2];
  }

  function unit(name) {
    return UNITS[lang][name];
  }

  function setLang(value) {
    lang = known(value) || "ru";
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) { /* приватный режим */ }
    document.documentElement.lang = lang;
    return lang;
  }

  function detect() {
    var saved;
    try { saved = localStorage.getItem(STORAGE_KEY); } catch (e) { saved = null; }
    if (known(saved)) return saved;
    var browser = (navigator.language || "ru").toLowerCase().slice(0, 2);
    return known(browser) || "ru";
  }

