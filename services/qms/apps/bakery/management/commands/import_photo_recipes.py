NEW_PRODUCTS = {
    "PHOTO-FAMILY-FROZEN": ("Семейный хлеб замороженный", Product.Category.BREAD),
    "PHOTO-LEPESHKA-KUNJUT": ("Лепешка с кунжутом", Product.Category.OTHER),
}


class Command(BaseCommand):
    help = "Импорт проверенных рецептур с фотографий технологических карт"

    def add_arguments(self, parser):
        parser.add_argument("--apply", action="store_true", help="Записать изменения; без флага выполняется проверка")

    @transaction.atomic
    def handle(self, *args, **options):
        apply_changes = options["apply"]
        created_products = created_ingredients = created_recipes = updated_recipes = 0

        for code, (name, category) in NEW_PRODUCTS.items():
            _, created = Product.objects.get_or_create(
                code=code,
                defaults={"name": name, "category": category, "unit": "шт", "is_active": True},
            )
            created_products += int(created)

        ingredient_by_source = {}
        for source_name, (code, name, unit) in INGREDIENTS.items():
            ingredient, created = Ingredient.objects.get_or_create(
                code=code,
                defaults={"name": name, "unit": unit, "is_active": True},
            )
            updates = []
            if ingredient.name != name:
                ingredient.name = name
                updates.append("name")
            if ingredient.unit != unit:
                ingredient.unit = unit
                updates.append("unit")
            if updates:
                ingredient.save(update_fields=updates + ["updated_at"])
            ingredient_by_source[source_name] = ingredient
            created_ingredients += int(created)

        for definition in RECIPES:
            # Одинаковый ингредиент может встречаться в тесте и посыпке — суммируем,
            # сохраняя пояснение в строке рецептуры.
            combined = {}
            for row in definition["items"]:
                source_name, amount, *row_notes = row
                key = ingredient_by_source[source_name].pk
                current = combined.setdefault(key, {"amount": Decimal("0"), "notes": []})
                current["amount"] += Decimal(amount)
                if row_notes:
                    current["notes"].append(row_notes[0])

            for product_code in definition["product_codes"]:
                product = Product.objects.get(code=product_code)
                recipe, created = Recipe.objects.get_or_create(
                    product=product,
                    version="1.0",
                    defaults={
                        "name": definition["title"],
                        "output_quantity": Decimal(str(definition["output"])),
                        "output_unit": "шт",
                        "is_active": True,
                    },
                )
                recipe.name = definition["title"]
                recipe.output_quantity = Decimal(str(definition["output"]))
                recipe.output_unit = "шт"
                recipe.is_active = True
                recipe.notes = "Источник: фотографии технологических карт. " + definition["notes"]
                recipe.save()
                recipe.items.all().delete()
                for sequence, (ingredient_id, data) in enumerate(combined.items(), start=1):
                    RecipeItem.objects.create(
                        recipe=recipe,
                        ingredient_id=ingredient_id,
                        quantity_for_batch=data["amount"],
                        sequence=sequence,
                        notes=", ".join(data["notes"]),
                    )
                created_recipes += int(created)
                updated_recipes += int(not created)

        self.stdout.write(
            f"products_created={created_products} ingredients_created={created_ingredients} "
            f"recipes_created={created_recipes} recipes_updated={updated_recipes}"
        )
        if not apply_changes:
            transaction.set_rollback(True)
            self.stdout.write(self.style.WARNING("DRY RUN: изменения отменены"))
        else:
            self.stdout.write(self.style.SUCCESS("Рецептуры импортированы"))
